function subarraySum(nums, k) {
  const seen = new Map([[0, 1]]); // prefix sum → how many times it occurred
  let prefix = 0;
  let count = 0;
  for (const x of nums) {
    prefix += x;
    count += seen.get(prefix - k) ?? 0;
    seen.set(prefix, (seen.get(prefix) ?? 0) + 1);
  }
  return count;
}
